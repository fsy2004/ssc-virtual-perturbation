def crop_white(img, threshold=250, pad=10):
    """Trim near-white borders from embedded raster panels."""
    arr = np.asarray(img)
    rgb = arr[..., :3]
    mask = np.any(rgb < threshold / 255 if rgb.dtype.kind == "f" else rgb < threshold, axis=2)
    if not mask.any():
        return arr
    y, x = np.where(mask)
    y0, y1 = max(int(y.min()) - pad, 0), min(int(y.max()) + pad + 1, arr.shape[0])
    x0, x1 = max(int(x.min()) - pad, 0), min(int(x.max()) + pad + 1, arr.shape[1])
    return arr[y0:y1, x0:x1]

