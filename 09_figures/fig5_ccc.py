    ax.set_title(
        f"{gene}: OR {r.OR:.2f} ({r.CI_low:.2f}-{r.CI_high:.2f}); BH q={r.q_BH:.3g}",
        fontsize=6.4,
    )
    ax.set_xticks([0, 1])
    ax.set_xticklabels(["HC", "SSc"], fontsize=6.8)
    ax.set_xlim(-0.45, 1.45)
    ax.set_ylim(-0.03, 1.03)
